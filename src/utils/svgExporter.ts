import { PlacedTool, GridfinityConfig } from '../types';
import {
  getBinDimensions,
  getTransformedContour,
  getMagnetPositions,
} from './geometry';
import { transformPocketContour } from './cutoutGeometry';
import { buildTextMultiPolygon, multiPolygonToPointRings } from './vectorText';

/**
 * Generates 1:1 scale SVG for laser cutting tool shadow foam or CNC router carving.
 * Layer 1 (Red stroke): Outer cut perimeter
 * Layer 2 (Blue stroke): Tool cavity cuts
 * Layer 3 (Magenta stroke): Negative pill finger pocket cuts
 * Layer 4 (Cyan stroke): Magnet / screw holes
 */
export function generateLaserCutSvg(config: GridfinityConfig, tools: PlacedTool[]): string {
  const { width, length } = getBinDimensions(config.gridX, config.gridY, config.gridZ, config.customHeightMm);

  let svg = `<?xml version="1.0" encoding="UTF-8"?>\n`;
  svg += `<svg xmlns="http://www.w3.org/2000/svg" width="${width}mm" height="${length}mm" viewBox="0 0 ${width} ${length}">\n`;
  svg += `  <!-- Generated by AI Gridfinity Studio - 1:1 Scale Vector Export -->\n`;
  svg += `  <style>\n`;
  svg += `    .outer-boundary { fill: none; stroke: #ff0000; stroke-width: 0.2; }\n`;
  svg += `    .tool-cavity { fill: #e2e8f0; stroke: #0000ff; stroke-width: 0.2; }\n`;
  svg += `    .finger-pocket { fill: #fed7aa; stroke: #ea580c; stroke-width: 0.2; stroke-dasharray: 1, 1; }\n`;
  svg += `    .magnet-hole { fill: none; stroke: #06b6d4; stroke-width: 0.2; }\n`;
  svg += `    .text-relief { fill: #a855f7; fill-opacity: 0.2; stroke: #7e22ce; stroke-width: 0.2; }\n`;
  svg += `    .dim-label { font-family: monospace; font-size: 3px; fill: #64748b; }\n`;
  svg += `  </style>\n`;

  // Outer boundary with 3.75mm corner radius
  svg += `  <!-- Layer: Outer Boundary -->\n`;
  svg += `  <rect class="outer-boundary" x="0" y="0" width="${width}" height="${length}" rx="3.75" ry="3.75" />\n`;

  // Magnet / Screw holes
  const magnetMode = config.magnetMode ?? (config.hasMagnets ? 'corners' : 'none');
  if (magnetMode !== 'none' || config.hasScrews) {
    const radius = magnetMode !== 'none' ? config.magnetDiameter / 2 : config.screwDiameter / 2;
    const magnets = getMagnetPositions(config.gridX, config.gridY, magnetMode !== 'none' ? magnetMode : 'corners');
    svg += `  <!-- Layer: Magnets / Screws (${magnetMode}) -->\n`;
    for (const m of magnets) {
      svg += `  <circle class="magnet-hole" cx="${m.x.toFixed(2)}" cy="${m.y.toFixed(2)}" r="${radius.toFixed(2)}" />\n`;
    }
  }

  // Tool Cavities
  svg += `  <!-- Layer: Tool Cavities -->\n`;
  for (const t of tools) {
    const pts = getTransformedContour(t);
    if (pts.length > 0) {
      const d = pts.map((p, i) => `${i === 0 ? 'M' : 'L'} ${p.x.toFixed(2)} ${p.y.toFixed(2)}`).join(' ') + ' Z';
      svg += `  <path class="tool-cavity" d="${d}" data-tool="${t.tool.name}" data-depth="${t.depthOverride ?? t.tool.depth}mm" />\n`;
    }

    // Finger Pockets
    const pockets = t.fingerPockets && t.fingerPockets.length > 0 ? t.fingerPockets : t.tool.fingerPockets;
    for (const pocket of pockets) {
      const pillPts = transformPocketContour(pocket, t, 8);
      const pillD = pillPts.map((p, i) => `${i === 0 ? 'M' : 'L'} ${p.x.toFixed(2)} ${p.y.toFixed(2)}`).join(' ') + ' Z';
      svg += `  <path class="finger-pocket" d="${pillD}" data-pocket="${pocket.id}" />\n`;
    }
  }

  // CAPSLOCK Label Text (Engrave / Emboss)
  if (config.textLabel && config.textLabel.mode !== 'none' && config.textLabel.text.trim().length > 0) {
    const mp = buildTextMultiPolygon(config.textLabel, { flipY: false });
    const polys = multiPolygonToPointRings(mp);
    svg += `  <!-- Layer: CAPSLOCK Text (${config.textLabel.mode}) -->\n`;
    for (const poly of polys) {
      const pathD = poly
        .map(
          (ring) =>
            ring.map((p, i) => `${i === 0 ? 'M' : 'L'} ${p.x.toFixed(2)} ${p.y.toFixed(2)}`).join(' ') + ' Z'
        )
        .join(' ');
      svg += `  <path class="text-relief" fill-rule="evenodd" d="${pathD}" />\n`;
    }
  }

  // 100mm Scale verification bar at bottom
  svg += `  <!-- 100mm Verification Scale Bar -->\n`;
  svg += `  <g transform="translate(5, ${length - 4})">\n`;
  svg += `    <line x1="0" y1="0" x2="100" y2="0" stroke="#0f172a" stroke-width="0.3" />\n`;
  svg += `    <line x1="0" y1="-1.5" x2="0" y2="1.5" stroke="#0f172a" stroke-width="0.3" />\n`;
  svg += `    <line x1="100" y1="-1.5" x2="100" y2="1.5" stroke="#0f172a" stroke-width="0.3" />\n`;
  svg += `    <text x="50" y="-1" text-anchor="middle" class="dim-label">100 mm scale check</text>\n`;
  svg += `  </g>\n`;

  svg += `</svg>\n`;
  return svg;
}

/**
 * Downloads generated SVG.
 */
export function downloadSvg(config: GridfinityConfig, tools: PlacedTool[], filename?: string) {
  const content = generateLaserCutSvg(config, tools);
  const blob = new Blob([content], { type: 'image/svg+xml;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename || `Gridfinity_${config.gridX}x${config.gridY}U_LaserFoam.svg`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
